#!/usr/bin/env python3
"""Standalone diagnostic: lists TokenVault's balance per currency, for every network
in the currently generated monitor set (i.e. the active SF_ENV - see tools/environments.ts).
Not an OZ Monitor trigger - run manually, e.g. before a docker-compose smoke test, to
sanity check on-chain state.

Network scope and the TokenVault address per network are both read from
config/monitors/<network>-totaldeposits.json rather than re-deriving them - those files
are generated by `npm run generate` (tools/generate-monitors.ts) for every chain in the
active SF_ENV, and already carry the real, non-hand-typed TokenVault address.

Usage: python3 config/triggers/scripts/list_token_vault_balances.py
Requires: web3, and the RPC env vars named in config/networks/*.json (e.g. from .env).
"""
import glob
import json
import os
from decimal import Decimal

from web3 import Web3

TOKEN_VAULT_ABI = [
    {
        "constant": True,
        "inputs": [],
        "name": "getCollateralCurrencies",
        "outputs": [{"name": "", "type": "bytes32[]"}],
        "stateMutability": "view",
        "type": "function",
    },
    {
        "constant": True,
        "inputs": [{"name": "_ccy", "type": "bytes32"}],
        "name": "getTokenAddress",
        "outputs": [{"name": "", "type": "address"}],
        "stateMutability": "view",
        "type": "function",
    },
]

ERC20_ABI = [
    {
        "constant": True,
        "inputs": [{"name": "account", "type": "address"}],
        "name": "balanceOf",
        "outputs": [{"name": "", "type": "uint256"}],
        "stateMutability": "view",
        "type": "function",
    },
    {
        "constant": True,
        "inputs": [],
        "name": "decimals",
        "outputs": [{"name": "", "type": "uint8"}],
        "stateMutability": "view",
        "type": "function",
    },
]


def decode_bytes32_string(hex_str):
    raw = bytes.fromhex(hex_str[2:] if hex_str.startswith("0x") else hex_str)
    return raw.rstrip(b"\x00").decode("utf-8", errors="replace")


def networks_in_active_env():
    for path in sorted(glob.glob(os.path.join("config", "monitors", "*-totaldeposits.json"))):
        network_slug = os.path.basename(path)[: -len("-totaldeposits.json")]
        with open(path) as f:
            monitor = json.load(f)
        yield network_slug, monitor["addresses"][0]["address"]


def main():
    networks = list(networks_in_active_env())
    if not networks:
        print(
            "no *-totaldeposits.json monitors found under config/monitors/ - "
            "run `npm run generate` first"
        )
        return

    for network_slug, token_vault_address in networks:
        print(f"=== {network_slug} (TokenVault {token_vault_address}) ===")

        with open(os.path.join("config", "networks", f"{network_slug}.json")) as f:
            network_config = json.load(f)
        rpc_url_env = network_config["rpc_urls"][0]["url"]["value"]

        w3 = Web3(Web3.HTTPProvider(os.environ[rpc_url_env]))
        token_vault_address = Web3.to_checksum_address(token_vault_address)
        token_vault = w3.eth.contract(address=token_vault_address, abi=TOKEN_VAULT_ABI)

        currencies = token_vault.functions.getCollateralCurrencies().call()
        for ccy_bytes32 in currencies:
            currency_name = decode_bytes32_string("0x" + ccy_bytes32.hex())
            token_address = token_vault.functions.getTokenAddress(ccy_bytes32).call()
            if int(token_address, 16) == 0:
                print(f"  {currency_name}: no token registered")
                continue

            token = w3.eth.contract(address=Web3.to_checksum_address(token_address), abi=ERC20_ABI)
            balance = token.functions.balanceOf(token_vault_address).call()
            decimals = token.functions.decimals().call()
            human_balance = format(Decimal(balance) / Decimal(10**decimals), "f")
            if "." in human_balance:
                human_balance = human_balance.rstrip("0").rstrip(".")
            print(f"  {currency_name}: {human_balance}")

        print()


if __name__ == "__main__":
    main()